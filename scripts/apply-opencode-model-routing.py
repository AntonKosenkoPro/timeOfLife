#!/usr/bin/env python3
"""Re-apply OpenCode model routing to openspec-generated command files.

Why this script exists: `.opencode/commands/opsx-*.md` are generated by
`openspec update` (full-file regeneration, verified against CLI 1.8.0) — any
hand edits there, including `model:` frontmatter, are wiped on the next
update. Routing for those generated files lives HERE as the single source of
truth. This script does NOT run automatically — MANUALLY re-run it after
every `openspec update`:

    python3 scripts/apply-opencode-model-routing.py

Files NOT managed here (pinned directly, survive `openspec update`):
  - `opencode.json` agent `lifio-implementer`
    (V2 `agents` entry, `opencode-go/muse-spark-1.3-contributor#xhigh`)
  - `.opencode/skills/process-pr/SKILL.md` delegation note in body
    (a skill body note cannot switch models — the pin takes effect only
    when invoked via `/opsx-pr`, whose command frontmatter sets the model)

Usage: python3 scripts/apply-opencode-model-routing.py
Idempotent: safe to run any time; reports what changed.
Exit code: 0 when all routed files end up correct, 1 on any I/O error.
"""

from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent.parent
COMMANDS = ROOT / ".opencode" / "commands"

# command name -> pinned model (provider/model#variant)
ROUTING = {
    "opsx-explore": "openai/gpt-6.1-sol#high",
    "opsx-propose": "openai/gpt-6.1-sol#high",
    "opsx-apply": "openai/gpt-6.1-sol#medium",
    "opsx-archive": "openai/gpt-6.1-sol#medium",
    "opsx-pr": "openai/gpt-6.1-sol#medium",
}

APPLY_NOTE = (
    "> Model routing: orchestrator runs on `openai/gpt-6.1-sol#medium`.\n"
    "> Delegate ALL code edits, repros, and test/verify runs to the\n"
    "> `lifio-implementer` subagent (`opencode-go/muse-spark-1.3-contributor#xhigh`)\n"
    "> via the subagent tool. Do not implement or run tests in the orchestrator session.\n"
)

# command name -> body note to enforce (None = no note).
# opsx-apply and opsx-pr share the same orchestrator/delegation note.
NOTES = {
    "opsx-apply": APPLY_NOTE,
    "opsx-pr": APPLY_NOTE,
}


def split_frontmatter(text: str):
    """Split markdown into (frontmatter_lines, body). Raises if no frontmatter."""
    lines = text.split("\n")
    if not lines or lines[0].strip() != "---":
        raise ValueError("missing frontmatter")
    for i in range(1, len(lines)):
        if lines[i].strip() == "---":
            return lines[1:i], "\n".join(lines[i + 1 :])
    raise ValueError("unterminated frontmatter")


def apply_pin(name: str, model: str) -> str:
    path = COMMANDS / f"{name}.md"
    text = path.read_text()
    fm, body = split_frontmatter(text)

    new_fm = [l for l in fm if not l.startswith("model:")]
    new_fm.insert(0, f"model: {model}")
    changed = new_fm != fm

    note = NOTES.get(name)
    if note:
        if note.strip() not in body:
            body = note + "\n" + body.lstrip("\n")
            changed = True
    out = "---\n" + "\n".join(new_fm) + "\n---\n" + body
    # Preserve trailing newline state of original
    if text.endswith("\n") and not out.endswith("\n"):
        out += "\n"
    if changed:
        path.write_text(out)
    return "updated" if changed else "ok"


def main() -> int:
    failed = False
    for name, model in ROUTING.items():
        try:
            status = apply_pin(name, model)
        except (OSError, ValueError) as e:
            print(f"{name}: ERROR ({e})")
            failed = True
            continue
        print(f"{name}: {status} ({model})")
    print(
        "owned files (pinned directly, not managed here): "
        "lifio-implementer agent, process-pr skill note"
    )
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
